/// All possible instance types.
#[derive(
    Serialize, Deserialize, Clone, Copy, EnumIter, Debug, PartialEq, Eq, PartialOrd, Ord, Hash,
)]
pub enum InstanceType {
    /// Runs continuously on hosts and responds to management requests from
    /// servers and clients.
    Agent,

    /// User interface for managing instances in the Sandpolis network.
    Client,

    /// Runs continously and coordinates interactions among instances in a
    /// Sandpolis network. All networks include at least one server
    /// instance.
    Server,
    // Probes are not technically instances, but they can connect to proper
    // agents/server instances and appear like standalone instances.
}

impl InstanceType {
    /// Each instance type has an identifier.
    pub const fn mask(&self) -> u8 {
        match self {
            InstanceType::Agent => 0b00000001,
            InstanceType::Client => 0b00000010,
            InstanceType::Server => 0b00000100,
        }
    }

    /// Each instance type has an associated color.
    pub const fn color(&self) -> colored::Color {
        match self {
            InstanceType::Agent => colored::Color::Cyan,
            InstanceType::Client => colored::Color::Green,
            InstanceType::Server => colored::Color::Magenta,
        }
    }
}

/// Names a capability a user can be granted, written as `"layer:action"`.
///
/// Permissions are granted layer-by-layer: `"shell:session"` allows opening
/// shell sessions, `"shell:*"` allows everything the shell layer offers, and
/// the bare wildcard `"*"` grants everything (there is no separate admin flag).
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(try_from = "String", into = "String")]
pub struct Permission {
    layer: String,
    action: String,
}

impl Permission {
    /// Whether this grant covers the given required permission.
    pub fn grants(&self, required: &Permission) -> bool {
        if self.layer == "*" {
            return true;
        }
        self.layer == required.layer && (self.action == "*" || self.action == required.action)
    }

    pub fn layer(&self) -> &str {
        &self.layer
    }

    pub fn action(&self) -> &str {
        &self.action
    }
}

impl FromStr for Permission {
    type Err = anyhow::Error;

    fn from_str(s: &str) -> Result<Self> {
        if s == "*" {
            return Ok(Self {
                layer: "*".to_string(),
                action: "*".to_string(),
            });
        }

        let Some((layer, action)) = s.split_once(':') else {
            bail!("invalid permission {s:?}: expected \"layer:action\" or \"*\"");
        };

        if layer.is_empty() || !layer.chars().all(|c| c.is_ascii_lowercase()) {
            bail!("invalid permission layer in {s:?}");
        }
        if action.is_empty()
            || !(action == "*"
                || action
                    .chars()
                    .all(|c| c.is_ascii_lowercase() || c == '_'))
        {
            bail!("invalid permission action in {s:?}");
        }

        Ok(Self {
            layer: layer.to_string(),
            action: action.to_string(),
        })
    }
}

impl TryFrom<String> for Permission {
    type Error = anyhow::Error;

    fn try_from(value: String) -> Result<Self> {
        value.parse()
    }
}

impl From<Permission> for String {
    fn from(value: Permission) -> Self {
        value.to_string()
    }
}

impl Display for Permission {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        if self.layer == "*" {
            f.write_str("*")
        } else {
            write!(f, "{}:{}", self.layer, self.action)
        }
    }
}

#[cfg(test)]
mod test_permission {
    use super::*;

    #[test]
    fn test_parse() {
        assert!("shell:session".parse::<Permission>().is_ok());
        assert!("shell:*".parse::<Permission>().is_ok());
        assert!("*".parse::<Permission>().is_ok());
        assert!("agent:power_off".parse::<Permission>().is_ok());

        assert!("".parse::<Permission>().is_err());
        assert!("shell".parse::<Permission>().is_err());
        assert!("shell:".parse::<Permission>().is_err());
        assert!(":session".parse::<Permission>().is_err());
        assert!("Shell:session".parse::<Permission>().is_err());
        assert!("shell:Session".parse::<Permission>().is_err());
        assert!("shell:session:extra".parse::<Permission>().is_err());
        assert!("*:session".parse::<Permission>().is_err());
    }

    #[test]
    fn test_grants() {
        let session: Permission = "shell:session".parse().unwrap();
        let execute: Permission = "shell:execute".parse().unwrap();

        assert!(session.grants(&session));
        assert!(!session.grants(&execute));

        let layer: Permission = "shell:*".parse().unwrap();
        assert!(layer.grants(&session));
        assert!(layer.grants(&execute));
        assert!(!layer.grants(&"desktop:session".parse().unwrap()));

        let all: Permission = "*".parse().unwrap();
        assert!(all.grants(&session));
        assert!(all.grants(&"desktop:session".parse().unwrap()));
    }

    #[test]
    fn test_round_trip() {
        for s in ["shell:session", "shell:*", "*"] {
            assert_eq!(s.parse::<Permission>().unwrap().to_string(), s);
        }
    }
}

/// Names a _layer_: the GUI face a subsystem presents, which the client's layer
/// picker chooses between and which notifications and services are attributed
/// to. A subsystem provides at most one, so the layer's name is the subsystem's
/// name (e.g. `"Shell"`, `"Inventory"`).
///
/// Layers are registered at runtime using the `inventory` crate.
#[cfg_attr(feature = "client", derive(bevy::prelude::Resource))]
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
pub struct LayerName(pub String);

impl LayerName {
    /// Create a new layer with the given name.
    pub const fn new(name: String) -> Self {
        Self(name)
    }

    /// Get the layer name.
    pub fn name(&self) -> &str {
        &self.0
    }

    /// Iterate over all registered layers.
    pub fn registered() -> impl Iterator<Item = &'static LayerName> {
        inventory::iter::<LayerName>()
    }
}

impl std::fmt::Display for LayerName {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}

impl std::ops::Deref for LayerName {
    type Target = str;

    fn deref(&self) -> &Self::Target {
        &self.0
    }
}

impl From<&str> for LayerName {
    fn from(s: &str) -> Self {
        Self(s.to_string())
    }
}

impl From<String> for LayerName {
    fn from(s: String) -> Self {
        Self(s)
    }
}

impl PartialEq<str> for LayerName {
    fn eq(&self, other: &str) -> bool {
        self.0 == other
    }
}

impl PartialEq<&str> for LayerName {
    fn eq(&self, other: &&str) -> bool {
        self.0 == *other
    }
}

